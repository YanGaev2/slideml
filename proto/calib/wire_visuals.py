from pathlib import Path

root = Path("F:/pptx-ai-native")


def patch(path, pairs):
    p = root / path
    s = p.read_text(encoding="utf-8")
    for a, b in pairs:
        assert a in s, (path, a[:70])
        s = s.replace(a, b, 1)
    p.write_text(s, encoding="utf-8")


